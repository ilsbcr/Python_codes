def remove_braces_and_sort(input_list):
    # Remove curly braces from each item in the list
    cleaned_list = [item.replace("{", "").replace("}", "") for item in input_list]
    
    # Sort the list
    sorted_list = sorted(cleaned_list)
    
    return sorted_list

